"""The Frappe handlers — the only module here that imports Frappe.

Generated by ``scripts/new_extension.py``.  A generic in-process CRUD backend
over this extension's DocTypes, so a generated repo works out of the box and
the developer replaces the parts that need domain judgement.

The tools run **in-process**, under the caller's own Frappe session.  A REST hop
would run as a service principal and see Administrator's permissions, so there
is no HTTP client here.
"""

from __future__ import annotations

from typing import Any

import frappe

from albanna_ai_chat.core.port import ToolContext, ToolResult
from albanna_ai_chat.core.tools import ToolSpec, compact_json, validate_arguments

SETTINGS_DOCTYPE = "Webshop Mcp Settings"

#: The tools this backend can run.
TOOL_NAMES = frozenset({"list_products", "get_product", "create_product", "update_product", "delete_product", "list_orders", "get_order"})


class WebshopMcpBackend:
    """Runs this extension's tools, in-process, as the caller."""

    def handles(self, name: str) -> bool:
        return name in TOOL_NAMES

    def call(
        self,
        spec: ToolSpec,
        arguments: dict[str, Any],
        context: ToolContext,
    ) -> ToolResult:
        problem = validate_arguments(spec, arguments)
        if problem:
            return ToolResult.failure(problem, error="invalid_arguments")

        handler = getattr(self, f"_run_{spec.name}", None)
        if handler is None:  # pragma: no cover
            return ToolResult.failure(
                f"{spec.name} is not implemented.", error="not_implemented"
            )
        return handler(arguments, context)

    # ------------------------------------------------------------------
    # reads
    # ------------------------------------------------------------------

    def _run_list(self, arguments: dict[str, Any], context: ToolContext) -> ToolResult:
        doctype = self._doctype_for("list")
        if not frappe.has_permission(doctype, "read"):
            return ToolResult.refusal(
                f"This account may not read {doctype}.", error="denied"
            )
        rows = frappe.get_list(
            doctype,
            filters=list(arguments.get("filters") or []),
            fields=arguments.get("fields") or ["name"],
            limit_page_length=arguments.get("limit") or 20,
        )
        return ToolResult.success(
            compact_json(rows), data=rows, summary=f"Found {len(rows)} {doctype}(s)"
        )

    def _run_get(self, arguments: dict[str, Any], context: ToolContext) -> ToolResult:
        doctype = self._doctype_for("get")
        name = arguments["name"]
        if not frappe.has_permission(doctype, "read", doc=name):
            return ToolResult.refusal(
                f"This account may not read {doctype}/{name}.", error="denied"
            )
        doc = frappe.get_doc(doctype, name)
        fields = arguments.get("fields")
        payload = {f: doc.get(f) for f in fields} if fields else doc.as_dict()
        return ToolResult.success(
            compact_json(payload), data=payload, summary=f"{doctype}/{name}"
        )

    # ------------------------------------------------------------------
    # writes
    # ------------------------------------------------------------------

    def _run_create(self, arguments: dict[str, Any], context: ToolContext) -> ToolResult:
        doctype = self._doctype_for("create")
        if not frappe.has_permission(doctype, "create"):
            return ToolResult.refusal(
                f"This account may not create {doctype}.", error="denied"
            )
        doc = frappe.get_doc({"doctype": doctype, **arguments["data"]})
        doc.insert()
        return ToolResult.success(
            compact_json({"name": doc.name}),
            data={"name": doc.name},
            summary=f"Created {doctype}/{doc.name}",
        )

    def _run_update(self, arguments: dict[str, Any], context: ToolContext) -> ToolResult:
        doctype = self._doctype_for("update")
        name = arguments["name"]
        if not frappe.has_permission(doctype, "write", doc=name):
            return ToolResult.refusal(
                f"This account may not change {doctype}/{name}.", error="denied"
            )
        doc = frappe.get_doc(doctype, name)
        if doc.docstatus == 1:
            return ToolResult.refusal(
                f"{doctype}/{name} is submitted and cannot be changed. It has "
                "to be cancelled and amended, which this tool does not do.",
                error="submitted",
            )
        for fieldname, value in arguments["data"].items():
            doc.set(fieldname, value)
        doc.save()
        return ToolResult.success(
            compact_json({"name": doc.name}), summary=f"Updated {doctype}/{name}"
        )

    def _run_delete(self, arguments: dict[str, Any], context: ToolContext) -> ToolResult:
        doctype = self._doctype_for("delete")
        name = arguments["name"]
        if not frappe.has_permission(doctype, "delete", doc=name):
            return ToolResult.refusal(
                f"This account may not delete {doctype}/{name}.", error="denied"
            )
        doc = frappe.get_doc(doctype, name)
        if doc.docstatus == 1:
            return ToolResult.refusal(
                f"{doctype}/{name} is submitted and must be cancelled first.",
                error="submitted",
            )
        frappe.delete_doc(doctype, name)
        return ToolResult.success(
            compact_json({"deleted": name}), summary=f"Deleted {doctype}/{name}"
        )

    # ------------------------------------------------------------------
    # helpers
    # ------------------------------------------------------------------

    def _doctype_for(self, kind: str) -> str:
        """The DocType a tool of *kind* acts on.

        The first one this extension owns.  A generated extension with several
        DocTypes needs this replaced with a real mapping — which is exactly the
        kind of decision the generator refuses to make.
        """
        from webshop_mcp.tools.manifest import DOCTYPES

        return DOCTYPES[0]


__all__ = ["WebshopMcpBackend"]
